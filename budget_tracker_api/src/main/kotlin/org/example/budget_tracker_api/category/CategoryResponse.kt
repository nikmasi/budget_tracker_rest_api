package org.example.budget_tracker_api.category

import io.swagger.v3.oas.annotations.media.Schema

@Schema(description = "Category details returned by the API")
data class CategoryResponse(

    @field:Schema(
        description = "Unique category identifier generated by the database",
        example = "1",
        accessMode = Schema.AccessMode.READ_ONLY
    )
    val id: Long,

    @field:Schema(
        description = "Category name",
        example = "Eating out"
    )
    val name: String,

    @field:Schema(
        description = "Category color in hexadecimal #RRGGBB format",
        example = "#FF5733"
    )
    val color: String
)