package org.example.budget_tracker_api.database

import io.swagger.v3.oas.annotations.media.Schema
import jakarta.persistence.Column
import jakarta.persistence.Entity
import jakarta.persistence.GeneratedValue
import jakarta.persistence.GenerationType
import jakarta.persistence.Id
import jakarta.persistence.Table
import jakarta.validation.constraints.NotBlank
import jakarta.validation.constraints.Pattern
import jakarta.validation.constraints.Size

@Schema(description = "A category used to organize income and expenses (database)")
@Entity
@Table(name = "category")
class Category(

    @field:Schema(
        description = "Unique identifier of the category, generated by the database (auto_increment).",
        example = "1",
        accessMode = Schema.AccessMode.READ_ONLY
    )
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    val id: Long? = null,

    @field:Schema(
        description = "Category name, 1–30 characters, unique ignoring case. Leading and trailing spaces are removed. A value is required ",
        example = "Eating out",
        minLength = 1,
        maxLength = 30,
        requiredMode = Schema.RequiredMode.REQUIRED
    )
    @field:NotBlank(message = "Name is required")
    @field:Size(min = 1, max = 30, message = "Name must be between 1 and 30 characters")
    @Column(nullable = false, unique = true, length = 30)
    var name: String,

    @field:Schema(
        description = "Category color in hexadecimal #RRGGBB format. A value is required.",
        example = "#FF5733",
        pattern = "^#[0-9A-Fa-f]{6}$",
        requiredMode = Schema.RequiredMode.REQUIRED
    )
    @field:NotBlank(message = "Color is required")
    @field:Pattern(regexp = "^#[0-9A-Fa-f]{6}$", message = "Color must be a valid hex color in form #RRGGBB")
    @Column(nullable = false, length = 7)
    var color: String,
)